export const RESEARCH: ResearchDef[] = [];
for (const [tree, rows] of [
  ['Finanzas', finance],
  ['Competición', competition],
  ['Relaciones', relations],
] as [Tree, Row[]][]) {
  const prev: Record<number, string> = {},
    counts: Record<number, number> = {};
  for (const [id, name, branch, effects, custom] of rows) {
    const row = counts[branch] || 0;
    RESEARCH.push({
      id,
      name,
      tree,
      branch,
      row,
      maxLevel: ['salary', 'sale', 'negotiator'].includes(id) ? 5 : 1,
      requires: custom ? custom.split(',') : prev[branch] ? [prev[branch]] : [],
      buildingLevel: Math.min(5, 1 + Math.floor(row / 2)),
      description: RESEARCH_STORIES[id],
      effects,
    });
    prev[branch] = id;
    counts[branch] = row + 1;
  }
}
